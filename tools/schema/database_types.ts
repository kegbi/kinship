/**
 * Generated Kysely database types.
 *
 * The canonical DDL in `personal-crm-schema/v7` is the only schema source of
 * truth. This tool derives `packages/backend/platform/postgres/generated/
 * database.ts` from it by introspecting a clean database that the repository's
 * own migration runner has just migrated, so the types can never say anything
 * the DDL does not. The file is written only by this tool and never by hand.
 *
 * Usage, through the task runner, which provisions and removes the disposable
 * PostgreSQL project and passes `DATABASE_URL`:
 *
 *   DENO_NO_PACKAGE_JSON=1 deno run --allow-read --allow-run=deno,docker,pnpm \
 *     tools/tasks/run.ts schema-types           # regenerate the file
 *   ... tools/tasks/run.ts schema-types --check # fail on drift, write nothing
 *
 * `deno task test:integration` runs the `--check` form against its own freshly
 * migrated database before the suites, so CI fails when the DDL and the
 * committed types differ.
 */

import { connectDatabase } from "../../packages/backend/platform/postgres/database.ts";

/** Where the generated types live, relative to the repository root. */
export const DATABASE_TYPES_PATH =
  "packages/backend/platform/postgres/generated/database.ts";

/** The generated-artifact header: the generator command and its source. */
export const DATABASE_TYPES_HEADER =
  "// Generated by tools/tasks/run.ts schema-types (kysely-codegen) from a database migrated to personal-crm-schema/v7. Do not edit.";

const ROOT = new URL("../../", import.meta.url);

/** The committed file for a generator body: the header, then the body. */
export function renderDatabaseTypes(body: string): string {
  return `${DATABASE_TYPES_HEADER}\n\n${body.trim()}\n`;
}

/**
 * Why the committed file differs from what the database generates, or
 * `undefined` when the two are byte-for-byte identical.
 */
export function databaseTypesDrift(
  expected: string,
  committed: string | undefined,
): string | undefined {
  if (committed === expected) return undefined;
  if (committed === undefined) {
    return `${DATABASE_TYPES_PATH} is missing; regenerate it with tools/tasks/run.ts schema-types.`;
  }
  const want = expected.split("\n");
  const have = committed.split("\n");
  let line = 0;
  while (line < want.length && want[line] === have[line]) line += 1;
  return [
    `${DATABASE_TYPES_PATH} differs from the migrated schema at line ${
      line + 1
    }.`,
    `  generated: ${JSON.stringify(want[line] ?? "<end of file>")}`,
    `  committed: ${JSON.stringify(have[line] ?? "<end of file>")}`,
    "Regenerate it with tools/tasks/run.ts schema-types; never edit it by hand.",
  ].join("\n");
}

/**
 * The types of every `crm` table, keyed `crm.<table>` the way adapters name
 * them, with snake_case columns because no adapter renames columns.
 */
async function introspect(url: string): Promise<string> {
  // The generator and its Postgres dialect load by path and only here: the
  // package index also loads the command-line interface, whose configuration
  // loader probes the home directory at import time, and the serializer reads
  // TypeScript's environment switches as it loads. Neither belongs in the
  // import graph of this module's pure helpers. The serializer's type parser
  // also `require`s `typescript` without declaring it, so `deno.json` pins
  // `npm:typescript@5.9.3` as a root dependency for it to resolve to.
  const [{ generate }, { PostgresDialect }] = await Promise.all([
    import("kysely-codegen/dist/generator/generator/generate.js"),
    import(
      "kysely-codegen/dist/generator/dialects/postgres/postgres-dialect.js"
    ),
  ]);
  const connection = connectDatabase(url);
  try {
    const body = await generate({
      db: connection.db,
      dialect: new PostgresDialect(),
      includePattern: "crm.*",
      outFile: null,
      skipAutogeneratedFileComment: true,
    });
    return renderDatabaseTypes(body);
  } finally {
    await connection.destroy();
  }
}

async function readCommitted(path: URL): Promise<string | undefined> {
  try {
    return await Deno.readTextFile(path);
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) return undefined;
    throw error;
  }
}

async function main(args: readonly string[]): Promise<void> {
  const url = Deno.env.get("DATABASE_URL");
  if (!url) throw new Error("DATABASE_URL names the migrated database.");
  const generated = await introspect(url);
  const target = new URL(DATABASE_TYPES_PATH, ROOT);
  if (args.includes("--check")) {
    const drift = databaseTypesDrift(generated, await readCommitted(target));
    if (drift) throw new Error(drift);
    console.log(`${DATABASE_TYPES_PATH} matches the migrated schema.`);
    return;
  }
  await Deno.mkdir(new URL(".", target), { recursive: true });
  await Deno.writeTextFile(target, generated);
  console.log(`Wrote ${DATABASE_TYPES_PATH}.`);
}

if (import.meta.main) {
  try {
    await main(Deno.args);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    Deno.exit(1);
  }
}

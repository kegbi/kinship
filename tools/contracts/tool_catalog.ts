/**
 * The agent tool catalog as one generated document (MCP-C2).
 *
 * `packages/contracts/mcp/tools.json` is what the public MCP guide renders
 * from: the server instructions, and for each tool its name, area, title,
 * description, the token scope it needs (`null` for any valid token), its
 * annotations, the route it calls, and the JSON Schema of its arguments —
 * the same schema the endpoint lists. It is self-contained so `apps/web` can
 * import it without the tool definitions, and stable-ordered (catalog order,
 * which the area files fix) so a rebuild of the same catalog is the same
 * text and `contracts:check` sees any drift.
 */

import { inputJsonSchema } from "../../packages/contracts/tools/define.ts";
import {
  AGENT_INSTRUCTIONS,
  TOOL_AREAS,
} from "../../packages/contracts/tools/mod.ts";
import { MCP_PATH } from "../../packages/contracts/routes/mcp.ts";
import { API_VERSION } from "../../packages/contracts/version.ts";

/** The generated catalog document. */
export function buildToolCatalog(): Record<string, unknown> {
  return {
    $comment:
      "Generated by tools/contracts/build.ts from packages/contracts/tools; do not edit. A null scope means any valid personal token may call the tool.",
    apiVersion: API_VERSION,
    endpoint: { method: "POST", path: MCP_PATH },
    instructions: AGENT_INSTRUCTIONS,
    areas: TOOL_AREAS.map((area) => ({
      id: area.id,
      title: area.title,
      tools: area.tools.map((tool) => tool.name),
    })),
    tools: TOOL_AREAS.flatMap((area) =>
      area.tools.map((tool) => ({
        name: tool.name,
        area: area.id,
        title: tool.title,
        description: tool.description,
        scope: tool.scope ?? null,
        annotations: tool.annotations,
        route: {
          operationId: tool.route.operationId,
          method: tool.route.method.toUpperCase(),
          path: tool.route.path,
        },
        inputSchema: inputJsonSchema(tool.input),
      }))
    ),
  };
}

/** The catalog as the committed file's text. */
export function renderToolCatalog(): string {
  return `${JSON.stringify(buildToolCatalog(), null, 2)}\n`;
}

/**
 * The compatibility barrel over the authored client.
 *
 * `apps/web` imports one hundred and twenty-four functions and a hundred and
 * fifty-odd type names from `packages/contracts/generated/auth-client.ts`, and
 * GAP-022 is not the ticket that renames them. The client itself now lives in
 * `packages/contracts/client/`, one module per surface, with every published
 * shape aliased from `generated/api-types.ts` — so the third hand-written copy
 * of every schema is gone — and this renders the barrel that keeps the old
 * import path and the old names working.
 *
 * The barrel is generated rather than written because it is a list: a function
 * added, removed, or renamed in a client module changes it, and
 * `deno task contracts:check` then fails until the committed artefact is
 * regenerated. `packages/contracts/client_test.ts` pins the names themselves,
 * so a rename cannot pass by regenerating.
 */

const CLIENT_DIRECTORY = new URL(
  "../../packages/contracts/client/",
  import.meta.url,
);

/** The surfaces the barrel re-exports, in the order it lists them. */
export const CLIENT_MODULES = [
  "request",
  "types",
  "today",
  "registration",
  "authentication",
  "invitations",
  "settings",
  "api_tokens",
  "integrations",
  "personal_lifecycle",
  "workspace_lifecycle",
  "files",
  "gifts",
  "journal",
  "imports",
  "exports",
  "people",
  "relationships",
  "interactions",
  "governance",
  "planning",
] as const;

const DECLARATION =
  /^export\s+(?:declare\s+)?(?:async\s+)?(interface|type|function|const|let)\s+(\w+)/;

/**
 * What the client modules share with each other but not with a caller.
 *
 * `request`, `workspaceHeader`, and `pageQuery` have to be exported for the
 * surface modules to use them, and none of them was ever part of the client's
 * published surface. The barrel leaves them out so `apps/web` sees exactly the
 * names it saw before.
 */
const INTERNAL = new Set(["pageQuery", "request", "workspaceHeader"]);

/** What one client module exports, split into what survives to runtime and what does not. */
export interface ModuleExports {
  readonly module: string;
  readonly values: readonly string[];
  readonly types: readonly string[];
}

/** Reads a module's exported names out of its source. */
export function moduleExports(module: string, source: string): ModuleExports {
  const values: string[] = [];
  const types: string[] = [];
  for (const line of source.split("\n")) {
    const declaration = DECLARATION.exec(line);
    if (!declaration) continue;
    const [, kind, name] = declaration;
    if (name === undefined || INTERNAL.has(name)) continue;
    if (kind === "interface" || kind === "type") types.push(name);
    else values.push(name);
  }
  return { module, values: values.sort(), types: types.sort() };
}

/** Reads every client module. */
export async function readClientModules(): Promise<readonly ModuleExports[]> {
  const modules: ModuleExports[] = [];
  for (const module of CLIENT_MODULES) {
    const source = await Deno.readTextFile(
      new URL(`${module}.ts`, CLIENT_DIRECTORY),
    );
    modules.push(moduleExports(module, source));
  }
  return modules;
}

/** Renders the barrel. */
export function renderClientBarrel(
  modules: readonly ModuleExports[],
): string {
  const lines = [
    "// Generated by deno task contracts:generate from packages/contracts/client. Do not edit.",
    "",
  ];
  for (const { module, values, types } of modules) {
    if (types.length > 0) {
      lines.push(
        `export type { ${types.join(", ")} } from "../client/${module}.ts";`,
      );
    }
    if (values.length > 0) {
      lines.push(
        `export { ${values.join(", ")} } from "../client/${module}.ts";`,
      );
    }
  }
  return lines.join("\n") + "\n";
}
